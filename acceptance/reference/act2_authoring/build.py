"""Act II authoring generator (authoring aid, never shown to the agent).

Renders, from the descriptions in cps.py (one spec function per checkpoint, taking the version n) and
copies1.py (Act I specs' updated copies at Act II mutations): every Act II spec and copy, the Act II
section of checkpoints.yaml, and acceptance/reference/scenarios_act2_data.py (the registry entries,
so every asserted figure comes from model.py with the spec's own seed). Re-run after any change:

    .venv/bin/python acceptance/reference/act2_authoring/build.py
"""
import os, sys, textwrap, pprint
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib
from lib import REPO, CPS, SPECFN, COPIES, REG, render
import cps  # noqa: F401  (registers the checkpoints)
import act1copies
import copies1  # noqa: F401

SPECS = os.path.join(REPO, 'acceptance/specs')
only = None
written = []
for c in CPS:
    spec = SPECFN[c['base']](c['n'])
    path = os.path.join(SPECS, c['base'] + '.spec.ts')
    open(path, 'w').write(render(spec))
    written.append(path)
for k, bases in sorted(COPIES.items()):
    for b in bases:
        spec = SPECFN[b](k)
        assert spec.copy_note, f'copy of {b} at {k} has no copy note'
        os.makedirs(os.path.join(SPECS, f'cp{k:02d}'), exist_ok=True)
        path = os.path.join(SPECS, f'cp{k:02d}', b + '.spec.ts')
        open(path, 'w').write(render(spec))
        written.append(path)
act1copies.write()

# registry data
with open(os.path.join(REPO, 'acceptance/reference/scenarios_act2_data.py'), 'w') as fh:
    fh.write('"""Generated by acceptance/reference/act2_authoring/build.py: Act II scenarios (spec, title, n, '
             'fixture, checks, label). Do not edit by hand."""\n')
    fh.write('DATA = ')
    fh.write(pprint.pformat(REG, width=110, sort_dicts=False))
    fh.write('\n')

# checkpoints.yaml: keep Act I, replace everything after it
y = open(os.path.join(REPO, 'checkpoints.yaml')).read()
marker = '  # ===================================================================== Act II: money over time'
marker3 = '  # ===================================================================== Act III: rules that interact'
rest = y[y.index(marker3):] if marker3 in y else ''   # Act III is written by act3_authoring/build.py
if marker in y:
    y = y[:y.index(marker)]
y = y.rstrip('\n') + '\n\n' + marker + '\n'
for c in CPS:
    y += f"  - id: {c['id']}\n    type: {c['type']}\n"
    if c['mutates']:
        y += f"    mutates: [{', '.join(str(m) for m in c['mutates'])}]\n"
    if c['retires']:
        y += '    retires:\n' + ''.join(f'      - "{r}"\n' for r in c['retires'])
    if c['algorithm']:
        y += f"    algorithm: {c['algorithm']}\n"
    y += f"    test: acceptance/specs/{c['base']}.spec.ts\n    request: |\n"
    text = ' '.join(textwrap.dedent(c['request']).split())
    for l in textwrap.wrap(text, 94):
        y += '      ' + l + '\n'
    y += '\n'
y = y.rstrip('\n') + '\n' + (('\n' + rest.rstrip('\n') + '\n') if rest else '')
open(os.path.join(REPO, 'checkpoints.yaml'), 'w').write(y)
print(f'wrote {len(written)} Act II spec files, {len(REG)} scenarios, {len(CPS)} checkpoints')

# last: wait for the panel after every row click that may replace an open invoice (all specs)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import panel_waits  # noqa: E402
panel_waits.main()
