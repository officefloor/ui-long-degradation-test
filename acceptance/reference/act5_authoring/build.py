"""Act V authoring generator (authoring aid, never shown to the agent).

Renders, from the descriptions in cps5.py (one spec function per checkpoint, taking the version n)
and copies5.py (earlier specs' updated copies at Act V mutations): every Act V spec and copy, the
Act V section of checkpoints.yaml, and acceptance/reference/scenarios_act5_data.py (the registry
entries, so every asserted figure comes from model.py with the spec's own seed). Re-run after any
change:

    .venv/bin/python acceptance/reference/act5_authoring/build.py
"""
import os, re, shutil, sys, textwrap, pprint
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lib5
from lib5 import REPO, CPS, SPECFN, COPIES, REG, render, NOTES, REPS, CUSTOM, FIRST
import cps  # noqa: F401  (Act II checkpoints: their spec functions, for copies)
import cps3  # noqa: F401  (Act III checkpoints)
import cps4  # noqa: F401  (Act IV checkpoints)
import cps5  # noqa: F401  (Act V checkpoints)
import copies5  # noqa: F401

SPECS = os.path.join(REPO, 'acceptance/specs')
# start clean: Act V's own specs and copy folders are all generated here
for name in os.listdir(SPECS):
    m = re.match(r'cp(\d+)', name)
    if m and int(m.group(1)) >= FIRST:
        path = os.path.join(SPECS, name)
        shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)

act5 = sorted((c for c in CPS if c['n'] >= FIRST), key=lambda c: c['n'])
written = []
for c in act5:
    spec = SPECFN[c['base']](c['n'])
    path = os.path.join(SPECS, c['base'] + '.spec.ts')
    open(path, 'w').write(render(spec))
    written.append(path)
for k, bases in sorted(COPIES.items()):
    if k < FIRST:
        continue
    for b in bases:
        spec = SPECFN[b](k)
        if (k, b) in NOTES:
            spec.copy_note = NOTES[(k, b)]
        assert spec.copy_note and spec.copy_note.startswith(f'UPDATED for cp{k} '), f'copy of {b} at {k} has no copy note'
        text = render(spec)
        for old, new in REPS.get((k, b), []):
            assert old in text, f'cp{k} copy of {b}: missing {old!r}'
            text = text.replace(old, new)
        if (k, b) in CUSTOM:
            text = CUSTOM[(k, b)](text)
        os.makedirs(os.path.join(SPECS, f'cp{k}'), exist_ok=True)
        path = os.path.join(SPECS, f'cp{k}', b + '.spec.ts')
        open(path, 'w').write(text)
        written.append(path)
written += lib5.write_text_copies()

with open(os.path.join(REPO, 'acceptance/reference/scenarios_act5_data.py'), 'w') as fh:
    fh.write('"""Generated by acceptance/reference/act5_authoring/build.py: Act V scenarios (spec, title, n, '
             'fixture, checks, label). Do not edit by hand."""\n')
    fh.write('DATA = ')
    fh.write(pprint.pformat(REG, width=110, sort_dicts=False))
    fh.write('\n')

y = open(os.path.join(REPO, 'checkpoints.yaml')).read()
marker = '  # ===================================================================== Act V: keep loading'
if marker in y:
    y = y[:y.index(marker)]
y = y.rstrip('\n') + '\n\n' + marker + '\n'
for c in act5:
    y += f"  - id: {c['id']}\n    type: {c['type']}\n"
    if c['mutates']:
        y += f"    mutates: [{', '.join(str(m) for m in c['mutates'])}]\n"
    if c['retires']:
        y += '    retires:\n' + ''.join(f'      - "{r}"\n' for r in c['retires'])
    if c['algorithm']:
        y += f"    algorithm: {c['algorithm']}\n"
    y += f"    test: acceptance/specs/{c['base']}.spec.ts\n    request: |\n"
    text = ' '.join(textwrap.dedent(c['request']).split())
    for l in textwrap.wrap(text, 94):
        y += '      ' + l + '\n'
    y += '\n'
open(os.path.join(REPO, 'checkpoints.yaml'), 'w').write(y.rstrip('\n') + '\n')
print(f'wrote {len(written)} Act V spec files, {len(REG)} scenarios, {len(act5)} checkpoints')

# last: wait for the panel after every row click that may replace an open invoice (all specs)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import panel_waits  # noqa: E402
panel_waits.main()
